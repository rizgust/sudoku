// Builds puzzles.js: a graded fallback bank plus practice puzzles for every technique.
// Run with:  bun tools/build-bank.js   (or node tools/build-bank.js)
const fs = require('fs');
const path = require('path');
const S = require('../sudoku.js');

const PER_TIER = 30;      // fallback puzzles per tier
const PER_TECH = 6;       // practice puzzles per technique (technique is the hardest one used)
const MAX_TRIES = 60000;

const rnd = S.mulberry32(20261116);
const tiers = { 1: [], 2: [], 3: [], 4: [], 5: [], 6: [] };
const practice = {};
for (const k of Object.keys(S.TECHNIQUES)) practice[k] = [];
const seen = new Set();

const done = () =>
  Object.values(tiers).every((a) => a.length >= PER_TIER) &&
  Object.values(practice).every((a) => a.length >= PER_TECH);

let tries = 0;
const t0 = Date.now();
while (!done() && tries < MAX_TRIES) {
  tries++;
  // Mostly minimal puzzles (rich in techniques); sometimes the gentler tiers.
  const want = tries % 5 === 0 ? 1 : tries % 5 === 1 ? 2 : 3;
  const g = S.generate(want, rnd);
  if (!g) continue;
  const str = S.toString(g.puzzle);
  if (seen.has(str)) continue;
  seen.add(str);
  const techs = Object.keys(g.techs);
  const entry = [g.level, str, techs.join(' ')];
  let used = false;
  const tierOk = g.level === 1 ? g.clues >= 36 : g.level === 2 ? g.clues <= 34 : true;
  if (tierOk && tiers[g.level].length < PER_TIER) { tiers[g.level].push(entry); used = true; }
  for (const t of techs) {
    if (S.TECHNIQUES[t].level === g.level && g.level >= 2 && practice[t].length < PER_TECH && !used) {
      practice[t].push(entry); used = true;
    }
  }
  if (tries % 2000 === 0) {
    console.log(tries, Object.values(tiers).map((a) => a.length).join('/'),
      Object.entries(practice).filter(([, a]) => a.length < PER_TECH).map(([k, a]) => `${k}:${a.length}`).join(' '));
  }
}

const all = [...Object.values(tiers).flat(), ...Object.values(practice).flat()];
console.log(`tries=${tries} entries=${all.length} in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
for (const [k, a] of Object.entries(practice)) if (a.length < PER_TECH) console.log('short:', k, a.length);

const out = `/* Generated by tools/build-bank.js. Do not edit by hand.
   [tier, puzzle (81 chars, "." = empty), techniques used]. Used as an instant fallback
   when live generation is slow, and as the source for technique practice. */
const PUZZLE_BANK = [
${all.map((e) => `  ${JSON.stringify(e)},`).join('\n')}
];
if (typeof module !== 'undefined') module.exports = PUZZLE_BANK;
`;
fs.writeFileSync(path.join(__dirname, '..', 'puzzles.js'), out);
